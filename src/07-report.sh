#!/usr/bin/env bash
set -Eeuo pipefail

# 07-report.sh — Generate markdown report from all results.
# Reads: results/qualifying.txt, results/bench/*.txt, results/eval/*/*.txt
# Outputs: markdown report to stdout (pipe to glow for pretty output)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RESULTS_DIR="${PIPELINE_RESULTS_DIR:-${SCRIPT_DIR}/results}"
SPEC_FILE="${SCRIPT_DIR}/specs.yaml"
QUALIFYING="${RESULTS_DIR}/qualifying.txt"
BENCH_DIR="${RESULTS_DIR}/bench"
EVAL_DIR="${RESULTS_DIR}/eval"

# --- Colors ---
if [[ -t 1 ]]; then
    CYAN='\033[0;36m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
else
    CYAN='' GREEN='' YELLOW='' RED='' NC=''
fi
log_info()  { printf "${CYAN}[*]${NC} %s\n" "$*" >&2; }
log_ok()    { printf "${GREEN}[+]${NC} %s\n" "$*" >&2; }
log_warn()  { printf "${YELLOW}[!]${NC} %s\n" "$*" >&2; }
log_err()   { printf "${RED}[-]${NC} %s\n" "$*" >&2; }
die() { log_err "$*"; exit 1; }

[[ -f "$QUALIFYING" ]] || die "Run 03-filter.sh first."
[[ -f "$SPEC_FILE" ]] || die "specs.yaml not found."

# --- Report header ---
echo "# Model Evaluation Report"
echo ""
echo "**Date:** $(date +%Y-%m-%d)"
gpu_name=$(yq -r '.hardware.gpu_name // "Unknown"' "$SPEC_FILE")
gpu_vram=$(yq -r '.hardware.gpu_vram_gb // "Unknown"' "$SPEC_FILE")
ram_gb=$(yq -r '.hardware.ram_gb // "Unknown"' "$SPEC_FILE")
cpu=$(yq -r '.hardware.cpu // "Unknown"' "$SPEC_FILE")
echo "**Hardware:** ${gpu_name} (${gpu_vram}GB VRAM), ${ram_gb}GB RAM, ${cpu}"
echo ""

# --- Qualifying models ---
echo "## Qualifying Models"
echo ""
echo "| Alias | Priority | Est. VRAM | Bench tok/s | Eval Score |"
echo "|-------|----------|-----------|-------------|------------|"

while IFS='|' read -r tag priority _source total_vram _vram_est; do
    safe_name=$(echo "$tag" | tr '/' '_')
    bench_file="${BENCH_DIR}/${safe_name}.txt"
    eval_dir="${EVAL_DIR}/${safe_name}"

    tok_s="N/A"
    if [[ -f "$bench_file" ]]; then
        extracted=$(grep -oP '^eval rate:\s*\K[0-9.]+' "$bench_file" 2>/dev/null | head -1 || true)
        [[ -n "$extracted" ]] && tok_s="$extracted"
    fi

    eval_status="pending"
    if [[ ! -d "$eval_dir" ]] || [[ ! -f "${eval_dir}/reasoning.txt" ]]; then
        eval_status="not run"
    fi

    echo "| $tag | $priority | ${total_vram}GB | $tok_s | $eval_status |"
done < "$QUALIFYING"

echo ""

# --- Benchmark details ---
echo "## Benchmark Results"
echo ""

for bench_file in "$BENCH_DIR"/*.txt; do
    [[ -f "$bench_file" ]] || continue
    alias=$(basename "$bench_file" .txt)
    echo "### $alias"
    echo ""
    echo '```'
    grep -E 'eval rate:|prompt eval rate:|eval count:|total duration:' "$bench_file" 2>/dev/null || echo "No metrics found"
    echo '```'
    echo ""
done

# --- Eval outputs ---
echo "## Evaluation Outputs"
echo ""

for eval_dir in "$EVAL_DIR"/*/; do
    [[ -d "$eval_dir" ]] || continue
    alias=$(basename "$eval_dir")
    echo "### $alias"
    echo ""
    for test in reasoning coding instruction; do
        if [[ -f "${eval_dir}/${test}.txt" ]]; then
            echo "**${test}:**"
            sed -n '/--- RESPONSE ---/,/--- END ---/p' "${eval_dir}/${test}.txt" 2>/dev/null | head -8
            echo ""
        fi
    done
done

echo "---"
echo "Generated by 07-report.sh"
